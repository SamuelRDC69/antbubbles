export type Locale = 'en' | keyof typeof DICTIONARIES

export function matchLocale(languages: readonly string[]): Locale {
  for (const language of languages) {
    const code = language.toLowerCase().split('-')[0]
    if (code === 'tl') return 'fil'
    if (code in DICTIONARIES) return code as Locale
  }
  return 'en'
}

export function translate(locale: Locale, key: TranslationKey, values: Record<string, string | number> = {}): string {
  const dictionary: Dictionary | undefined = locale === 'en' ? undefined : DICTIONARIES[locale]
  const template = dictionary?.[key] ?? ENGLISH[key]
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
}

